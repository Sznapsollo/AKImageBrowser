function resolveLanguage(preference) {
	if(translations[preference]) {
		return preference;
	}
	var browser = String((navigator.languages && navigator.languages[0]) || navigator.language || 'en').toLowerCase();
	return translations[browser.split('-')[0]] ? browser.split('-')[0] : 'en';
}

function pluralIndex(language, count) {
	if(language === 'pl') {
		if(count === 1) {
			return 0;
		}
		var lastDigit = count % 10;
		var lastTwo = count % 100;
		return lastDigit >= 2 && lastDigit <= 4 && (lastTwo < 12 || lastTwo > 14) ? 1 : 2;
	}
	return count === 1 ? 0 : 1;
}

function translate(language, key, params, count) {
	var value = translations[language][key];
	if(value === undefined) {
		value = translations.en[key];
	}
	if(Array.isArray(value)) {
		value = value[Math.min(value.length - 1, pluralIndex(language, count === undefined ? 1 : count))];
	}
	return String(value).replace(/\{(\w+)\}/g, function(match, name) {
		return params && params[name] !== undefined ? params[name] : match;
	});
}
